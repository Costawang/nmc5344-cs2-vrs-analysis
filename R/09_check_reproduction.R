fixed <- c("data/processed/vrs_team_details.csv", "data/processed/vrs_regions.csv", "data/processed/vrs_winnings.csv",
           list.files("data/processed", "^vrs_match_inputs_.*csv.gz$", full.names = TRUE))
before <- vapply(fixed, file_hash, character(1))
