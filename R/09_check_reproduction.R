source("R/02_parse_standings.R"); parse_standings()
source("R/03_parse_details.R"); parse_details()
after <- vapply(fixed, file_hash, character(1))
reproduction <- tibble(file = fixed, previous_sha256 = unname(before), fresh_sha256 = unname(after), identical = before == after)
save_csv(reproduction, "output/validation/reproduction.csv")
stopifnot(all(reproduction$identical))
